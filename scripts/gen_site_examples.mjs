// Regenerates ../site/examples: the specifications offered by the demo page, with their data inlined.
// Official examples come from the vega-lite tag (run `node fetch_examples.mjs` first), the others from ../examples.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSpec } from './lib/spec.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const officialDir = path.join(root, 'scripts/.cache/vega-lite-5.23.0/examples/specs');
const out = path.join(root, 'site/examples');

const official = (name, title, group) => ({ id: name, title, group, spec: () => loadSpec(path.join(officialDir, name + '.vl.json')) });
const local = (file, id, title, group) => ({ id, title, group, spec: () => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8')) });
const literal = (id, title, group, spec) => ({ id, title, group, spec: () => spec });

const tiny = { values: [{ a: 'A', b: 28 }, { a: 'B', b: 55 }, { a: 'C', b: 43 }] };
const bar = { x: { field: 'a', type: 'nominal' }, y: { field: 'b', type: 'quantitative' } };

const G = { basic: 'Charts', layer: 'Layers', frame: 'Generated by MoonFrame', error: 'Not supported (shows the error)' };
const entries = [
  official('bar', 'Bar chart', G.basic),
  official('bar_aggregate', 'Aggregated horizontal bars', G.basic),
  official('stacked_bar_v', 'Stacked bars with a colour legend', G.basic),
  official('point_color', 'Scatter plot with a colour legend', G.basic),
  official('point_ordinal_color', 'Ordinal colour', G.basic),
  official('point_log', 'Log scale', G.basic),
  official('arc_pie', 'Pie chart', G.basic),
  official('arc_donut', 'Donut chart', G.basic),
  local('examples/arc_aggregate.vl.json', 'arc_aggregate', 'Rounded donut with padding', G.basic),
  local('examples/channel_binned_count_size.vl.json', 'binned_count_size', 'Binned circles sized by count', G.basic),
  official('layer_bar_line', 'Bars and a line', G.layer),
  official('layer_histogram', 'Shared bins in two layers', G.layer),
  official('layer_rect_extent', 'A rect over the extent', G.layer),
  official('layer_bar_annotations', 'Annotated bars', G.layer),
  official('layer_circle_independent_color', 'Independent legends', G.layer),
  official('layer_color_legend_left', 'Legend on the left (time axis)', G.layer),
  local('examples/layer_independent_y.vl.json', 'layer_independent_y', 'Two y scales, two axes', G.layer),
  local('examples/moonframe_demo/out/revenue_by_region.vl.json', 'moonframe_revenue_by_region', 'Revenue by region (CSV → MoonFrame)', G.frame),
  local('examples/moonframe_demo/out/revenue_by_month.vl.json', 'moonframe_revenue_by_month', 'Revenue by month (CSV → MoonFrame)', G.frame),
  local('examples/moonframe_demo/out/units_vs_price.vl.json', 'moonframe_units_vs_price', 'Units against price (CSV → MoonFrame)', G.frame),
  local('examples/moonframe/bar_stacked.vl.json', 'moonframe_bar_stacked', 'Stacked bars (MoonFrame)', G.frame),
  literal('error_params', 'params (interaction)', G.error, { data: tiny, params: [{ name: 'p', select: 'point' }], mark: 'bar', encoding: bar }),
  literal('error_facet', 'facet', G.error, { data: tiny, facet: { row: { field: 'a', type: 'nominal' } }, spec: { mark: 'bar', encoding: bar } }),
  literal('error_corner_radius', 'mark.cornerRadius', G.error, { data: tiny, mark: { type: 'bar', cornerRadius: 4 }, encoding: bar }),
];

// Pretty-print: small values on one line, rows of data.values one per line.
const inline = (v) => Array.isArray(v) ? '[' + v.map(inline).join(', ') + ']'
  : v && typeof v === 'object' ? '{' + Object.entries(v).map(([k, x]) => JSON.stringify(k) + ': ' + inline(x)).join(', ') + '}'
  : JSON.stringify(v);
const isRow = (v) => v && typeof v === 'object' && !Array.isArray(v) && Object.values(v).every((x) => x === null || typeof x !== 'object');
function fmt(v, ind) {
  const flat = inline(v);
  const pad = '  '.repeat(ind + 1), end = '  '.repeat(ind);
  if (Array.isArray(v)) {
    if (v.length === 0) return '[]';
    if (v.every(isRow) && v.length > 1) return '[\n' + v.map((r) => pad + inline(r)).join(',\n') + '\n' + end + ']';
    if (flat.length <= 72) return flat;
    return '[\n' + v.map((x) => pad + fmt(x, ind + 1)).join(',\n') + '\n' + end + ']';
  }
  if (v && typeof v === 'object') {
    if (flat.length <= 72) return flat;
    return '{\n' + Object.entries(v).map(([k, x]) => pad + JSON.stringify(k) + ': ' + fmt(x, ind + 1)).join(',\n') + '\n' + end + '}';
  }
  return flat;
}

fs.mkdirSync(out, { recursive: true });
for (const f of fs.readdirSync(out)) fs.unlinkSync(path.join(out, f));
const index = [];
for (const e of entries) {
  const spec = e.spec();
  delete spec.$schema;
  fs.writeFileSync(path.join(out, e.id + '.vl.json'), fmt(spec, 0) + '\n');
  index.push({ id: e.id, title: e.title, group: e.group, file: e.id + '.vl.json' });
}
fs.writeFileSync(path.join(out, 'index.json'), JSON.stringify(index, null, 2) + '\n');
console.log(`wrote ${entries.length} examples to site/examples`);
